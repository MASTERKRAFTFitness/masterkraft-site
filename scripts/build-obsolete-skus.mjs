#!/usr/bin/env node
// Regenerate src/lib/obsolete-skus.json — the list of Unleashed product codes
// that must never be served on the site.
//
// Run:  npm run build:obsolete      (then commit the JSON)
//
// WHY THIS IS A BUILD STEP AND NOT A RUNTIME FETCH. Reading obsolescence at
// request time meant asking Unleashed for its whole catalogue INCLUDING obsolete
// records, which is 10 pages instead of 6. Unleashed answers in ~2.5s per page
// and throttles concurrency, so that added ~6s to every cold render of every
// listing page. The flag changes when someone retires a product in the ERP,
// which is a handful of times a year, so it belongs in the repo.
//
// THE TRAP: GET /Products HIDES OBSOLETE PRODUCTS BY DEFAULT. Without
// includeObsolete=true it returns 1,092 items, every one reporting
// Obsolete:false, which reads as "this company never uses the flag". With it,
// 1,892 of which 800 are obsolete. The field is `Obsolete`, not `IsObsolete`.
//
// RE-RUN THIS when the ERP retires a product, or the site will keep selling it.
// `npm run check:obsolete` reports drift without writing anything.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { fetchAllProducts } from "./lib/erp-products.mjs";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "src/lib/obsolete-skus.json");

function env(name) {
  if (process.env[name]) return process.env[name];
  const text = readFileSync(join(ROOT, ".env.local"), "utf8");
  for (const line of text.split("\n")) {
    const eq = line.indexOf("=");
    if (eq > 0 && line.slice(0, eq).trim() === name) {
      return line.slice(eq + 1).trim().replace(/^["']|["']$/g, "");
    }
  }
  throw new Error(`Missing ${name} (environment or .env.local)`);
}

const API_ID = env("UNLEASHED_API_ID");
const API_KEY = env("UNLEASHED_API_KEY");

// Paging moved to scripts/lib/erp-products.mjs on 2026-09-18, sequential and
// with retries. The parallel version this file used to hold 502'd against a
// degraded ERP and failed two deploys that had nothing to do with it.
const { items } = await fetchAllProducts({
  apiId: API_ID,
  apiKey: API_KEY,
  log: (line) => console.error(line),
});

// SELLING THROUGH. Obsolete in the ERP so nothing is reordered, but still on the
// site as clearance until the stock is gone (Michael, 2026-10-15). All eight are
// Obsolete:true with IsSellable:true - the ERP's way of saying "stop buying,
// keep selling". Take a code out of this list once its stock reaches zero, then
// re-run this script; check:obsolete will flag the drift until you do.
const SELL_THROUGH = new Set([
  "MCBIAR01", // Air Bike Classic
  "MCBIAR02", // Air Bike Pro
  "MCBIAR04", // Air Cycle Pro
  "MCRWAR03", // Air Rower Elite
  "MCTMSP01", // Curved Treadmill Pro
  "MCSTAR01", // Ski Trainer Pro
  "MCSTACC01", // Ski Trainer Floor Stand
  "MCSTACC02", // Ski Trainer Wall Mount Bracket
]);

// Obsolete OR explicitly not sellable: both mean "do not put this in front of a
// customer", and the two overlap almost entirely in practice. Not-sellable
// always wins; the sell-through list only overrides the Obsolete flag.
const retired = items
  .filter(
    (p) =>
      p.IsSellable === false ||
      (p.Obsolete === true && !SELL_THROUGH.has(String(p.ProductCode).toUpperCase())),
  )
  .map((p) => String(p.ProductCode).toUpperCase())
  .sort();

if (items.length < 1500) {
  // A short read means includeObsolete didn't apply (or the API paged short) and
  // we are about to write a list that silently un-retires products.
  console.error(
    `Refusing to write: only ${items.length} products came back, expected ~1,900 ` +
      `with obsolete records included. Not overwriting ${OUT}.`
  );
  process.exit(1);
}

const previous = (() => {
  try {
    return JSON.parse(readFileSync(OUT, "utf8"));
  } catch {
    return { codes: [] };
  }
})();

writeFileSync(
  OUT,
  JSON.stringify(
    {
      _comment:
        "GENERATED by scripts/build-obsolete-skus.mjs — do not edit by hand. " +
        "Unleashed product codes that must never be served. Re-run when the ERP retires a product.",
      generatedFrom: `${items.length} Unleashed products`,
      codes: retired,
    },
    null,
    2
  ) + "\n"
);

const added = retired.filter((c) => !previous.codes.includes(c));
const removed = (previous.codes ?? []).filter((c) => !retired.includes(c));
console.log(`Unleashed: ${items.length} products, ${retired.length} obsolete or unsellable`);
console.log(`Wrote ${OUT}`);
if (added.length) console.log(`  + ${added.length} newly retired: ${added.slice(0, 10).join(", ")}`);
if (removed.length) console.log(`  - ${removed.length} no longer retired: ${removed.slice(0, 10).join(", ")}`);
if (!added.length && !removed.length) console.log("  no change");

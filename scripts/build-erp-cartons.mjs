#!/usr/bin/env node
// Regenerate src/lib/erp-cartons.json — every Unleashed product code that has a
// COMPLETE carton, so a synchronous chokepoint can ask the ERP without awaiting
// it.
//
// Run:  npm run build:cartons      (then commit the JSON)
//       npm run check:cartons      (drift only, writes nothing)
//
// WHY THIS EXISTS. lib/woocommerce decides what the site LISTS, and it is
// synchronous, snapshot-only and imported by everything - it cannot await
// getUnleashedMap(). So it used to judge shippability on the frozen WooCommerce
// carton alone, while freight quotes from the snapshot OR the ERP. A product
// whose snapshot carton is wrong and whose ERP carton is right was therefore
// dropped from every listing for a fault the checkout never suffers. That is not
// hypothetical: ABPBSB04, the 12" foam plyo box, is recorded in the snapshot as
// 850 x 1000 x 305 - millimetres, where the rest of the file is centimetres - so
// it measures 259 cubic metres and fails the 3 m3 bound. The ERP holds the same
// box correctly at 85 x 100 x 30.5. See reports/carton-unit-fix-*.csv, where
// that code was corrected IN UNLEASHED and the snapshot kept the old value.
//
// This is the same argument obsolete-skus.json already makes, and the same
// shape: ERP truth, committed, so a module that cannot fetch can still consult
// it. Re-run when the ERP's cartons change.
//
// THE AXIS ORDER IS NOT length/width/height. Unleashed stores Width/Depth/Height
// and they do not map onto the snapshot's axes - see lib/unleashed. That does not
// matter to the only question asked of this file (are all three sides in bounds,
// and is the volume under the cap), both of which are order-independent. It
// would matter to anything that builds a consignment, so do not use this for
// that: lib/freight-server is where a carton is chosen for a quote.
import crypto from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(ROOT, "src/lib/erp-cartons.json");
const CHECK = process.env.CHECK === "1";

function env(name) {
  if (process.env[name]) return process.env[name];
  const text = readFileSync(join(ROOT, ".env.local"), "utf8");
  for (const line of text.split("\n")) {
    const eq = line.indexOf("=");
    if (eq > 0 && line.slice(0, eq).trim() === name) {
      return line.slice(eq + 1).trim().replace(/^["']|["']$/g, "");
    }
  }
  throw new Error(`Missing ${name} (environment or .env.local)`);
}

const API_ID = env("UNLEASHED_API_ID");
const API_KEY = env("UNLEASHED_API_KEY");

async function page(n) {
  // includeObsolete=true for the same reason build-obsolete-skus.mjs passes it:
  // GET /Products hides retired records, and a retired product still has a
  // carton worth knowing about while its page is being wound down.
  const query = "pageSize=200&includeObsolete=true";
  const res = await fetch(`https://api.unleashedsoftware.com/Products/${n}?${query}`, {
    headers: {
      "api-auth-id": API_ID,
      "api-auth-signature": crypto.createHmac("sha256", API_KEY).update(query).digest("base64"),
      Accept: "application/json",
      "User-Agent": "Mozilla/5.0", // Unleashed's WAF rejects some default agents
    },
  });
  if (!res.ok) throw new Error(`Unleashed ${res.status} on Products/${n}`);
  return res.json();
}

const first = await page(1);
const pages = first.Pagination?.NumberOfPages ?? 1;
const items = [...first.Items];
for (const p of await Promise.all(Array.from({ length: pages - 1 }, (_, i) => page(i + 2)))) {
  items.push(...p.Items);
}

if (items.length < 1500) {
  console.error(
    `Refusing to write: only ${items.length} products came back, expected ~2,400 ` +
      `with obsolete records included. Not overwriting ${OUT}.`
  );
  process.exit(1);
}

const num = (v) => {
  const n = parseFloat(String(v ?? "").replace(/[^0-9.]/g, ""));
  return Number.isFinite(n) && n > 0 ? n : 0;
};

// Only COMPLETE cartons. A partial one cannot answer the question this file
// exists for, and recording it would invite a caller to treat a missing side as
// a zero.
const cartons = {};
for (const p of items) {
  const kg = num(p.Weight);
  const w = num(p.Width);
  const d = num(p.Depth);
  const h = num(p.Height);
  if (!kg || !w || !d || !h) continue;
  cartons[String(p.ProductCode).toUpperCase()] = [kg, w, d, h];
}

const json =
  JSON.stringify(
    {
      _comment:
        "GENERATED by scripts/build-erp-cartons.mjs - do not edit by hand. " +
        "Unleashed ProductCode -> [weightKg, widthCm, depthCm, heightCm]. " +
        "Axis order is the ERP's, not the snapshot's - see the script header.",
      generatedFrom: `${items.length} Unleashed products`,
      cartons: Object.fromEntries(Object.entries(cartons).sort(([a], [b]) => a.localeCompare(b))),
    },
    null,
    2
  ) + "\n";

const previous = (() => {
  try {
    return readFileSync(OUT, "utf8");
  } catch {
    return "";
  }
})();

if (CHECK) {
  if (previous !== json) {
    console.error(`\n  ${OUT} is out of date - run \`npm run build:cartons\` and commit it.\n`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date (${Object.keys(cartons).length} cartons)`);
  process.exit(0);
}

writeFileSync(OUT, json);
console.log(`Unleashed: ${items.length} products, ${Object.keys(cartons).length} with a complete carton`);
console.log(`Wrote ${OUT}`);
